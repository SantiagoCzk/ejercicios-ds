"use strict";
/*
    Crear una función que reciba dos valores y retorne su
    multiplicación. Mostrar el resultado por consola.
*/
function multplicacion(a, b) {
    return a * b;
}
let numero1 = 2;
let numero2 = 5;
console.log(`Resultado de multiplicar ${numero1} y ${numero2}: ${multplicacion(numero1, numero2)}`);
